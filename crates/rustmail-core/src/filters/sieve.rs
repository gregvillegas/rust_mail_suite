//! Turns rules and the autoresponder into Sieve scripts (RFC 5228).
//!
//! Three scripts live in a user's Sieve directory:
//!
//! | Name | Content | Written by |
//! |------|---------|-----------|
//! | [`MAIN_SCRIPT`] | includes the two below; the only active script | RustMail |
//! | [`VACATION_SCRIPT`] | the autoresponder | the autoresponder page |
//! | [`FILTERS_SCRIPT`] | the user's rules, or a hand-written script | the filters pages |
//!
//! The includes are `:optional`, so installing one script never fails because the other
//! has not been written yet. Keeping them apart means the rule builder, the raw editor and the autoresponder
//! never overwrite each other.

use super::{Action, Autoresponder, Condition, Field, Op, Rule};

/// The active script. It only includes the other two.
pub const MAIN_SCRIPT: &str = "rustmail";
/// The autoresponder script.
pub const VACATION_SCRIPT: &str = "rustmail-vacation";
/// The filters script.
pub const FILTERS_SCRIPT: &str = "rustmail-filters";

/// Quotes `text` as a Sieve string. Backslash and double quote are escaped; callers
/// reject control characters beforehand (see [`super::Rule::validate`]).
#[must_use]
pub fn quote(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        if c == '"' || c == '\\' {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

/// The active script: runs the autoresponder, then the filters.
#[must_use]
pub fn main_script() -> String {
    format!(
        "# Managed by RustMail Suite. Do not edit; use the filter pages.\n\
         require [\"include\"];\n\
         include :personal :optional {};\n\
         include :personal :optional {};\n",
        quote(VACATION_SCRIPT),
        quote(FILTERS_SCRIPT)
    )
}

fn test_for(c: &Condition) -> String {
    let (kind, header) = match c.field {
        Field::From => ("address", "from"),
        Field::To => ("address", "to"),
        Field::Cc => ("address", "cc"),
        Field::Subject => ("header", "subject"),
        Field::ListId => ("header", "list-id"),
    };
    let op = match c.op {
        Op::Contains => ":contains".to_owned(),
        Op::Is => ":is".to_owned(),
        Op::StartsWith | Op::EndsWith => ":matches".to_owned(),
    };
    // starts_with / ends_with use wildcards, so the user's own `*` and `?` must be escaped.
    let value = match c.op {
        Op::StartsWith => format!("{}*", escape_wildcards(&c.value)),
        Op::EndsWith => format!("*{}", escape_wildcards(&c.value)),
        _ => c.value.clone(),
    };
    let all = if kind == "address" { " :all" } else { "" };
    format!("{kind} {op}{all} {} {}", quote(header), quote(&value))
}

fn escape_wildcards(text: &str) -> String {
    text.replace('\\', "\\\\")
        .replace('*', "\\*")
        .replace('?', "\\?")
}

/// Whether the rules need the `imap4flags` / `mailbox` extensions.
fn requires(rules: &[&Rule]) -> Vec<&'static str> {
    let mut needed = Vec::new();
    let any = |f: fn(&Action) -> bool| rules.iter().any(|r| r.actions.iter().any(f));
    if any(|a| matches!(a, Action::MoveTo { .. })) {
        needed.push("fileinto");
        needed.push("mailbox");
    }
    if any(|a| matches!(a, Action::MarkRead)) {
        needed.push("imap4flags");
    }
    needed
}

/// The script for the rule list. Disabled rules are left out.
///
/// The rules are assumed valid ([`super::validate_rules`]).
#[must_use]
pub fn rules_script(rules: &[Rule]) -> String {
    let active: Vec<&Rule> = rules.iter().filter(|r| r.enabled).collect();
    let mut out = String::from("# Generated by RustMail Suite from the filter rules. Edits made here are lost\n# the next time the rules are saved; use the advanced editor to take over.\n");
    let needed = requires(&active);
    if !needed.is_empty() {
        let list: Vec<String> = needed.iter().map(|n| quote(n)).collect();
        out.push_str(&format!("require [{}];\n", list.join(", ")));
    }
    for rule in active {
        out.push_str(&format!(
            "\n# Rule: {}\n",
            rule.name.replace(['\r', '\n'], " ")
        ));
        let tests: Vec<String> = rule.conditions.iter().map(test_for).collect();
        let body = actions_text(&rule.actions);
        match tests.as_slice() {
            [one] => out.push_str(&format!("if {one} {{\n{body}}}\n")),
            many => {
                let join = if rule.match_all { "allof" } else { "anyof" };
                let inner: Vec<String> = many.iter().map(|t| format!("  {t}")).collect();
                out.push_str(&format!(
                    "if {join}(\n{}\n) {{\n{body}}}\n",
                    inner.join(",\n")
                ));
            }
        }
    }
    out
}

fn actions_text(actions: &[Action]) -> String {
    // Flags first: `addflag` only affects what a later `fileinto` or `keep` stores.
    let mut ordered: Vec<&Action> = actions
        .iter()
        .filter(|a| matches!(a, Action::MarkRead))
        .collect();
    ordered.extend(
        actions
            .iter()
            .filter(|a| !matches!(a, Action::MarkRead | Action::Stop)),
    );
    ordered.extend(actions.iter().filter(|a| matches!(a, Action::Stop)));
    let mut out = String::new();
    for a in ordered {
        let line = match a {
            Action::MarkRead => "addflag \"\\\\Seen\";".to_owned(),
            Action::MoveTo { folder } => format!("fileinto :create {};", quote(folder)),
            Action::Discard => "discard;".to_owned(),
            Action::Forward { address } => format!("redirect :copy {};", quote(address)),
            Action::Stop => "stop;".to_owned(),
        };
        out.push_str("  ");
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// The autoresponder script. `addresses` are the user's own addresses (login and
/// aliases): Dovecot answers only mail addressed to one of them.
///
/// A disabled or empty autoresponder gives a script that does nothing.
#[must_use]
pub fn vacation_script(settings: &Autoresponder, addresses: &[String]) -> String {
    if !settings.enabled {
        return "# The autoresponder is off.\n".to_owned();
    }
    let mut out = String::from(
        "# Generated by RustMail Suite from the autoresponder page.\nrequire [\"vacation\"",
    );
    let dated = settings.starts_on.is_some() || settings.ends_on.is_some();
    if dated {
        out.push_str(", \"date\", \"relational\"");
    }
    out.push_str("];\n\n");
    let mut tests = Vec::new();
    if let Some(s) = settings.starts_on {
        tests.push(format!(
            "currentdate :value \"ge\" \"date\" {}",
            quote(&s.format("%Y-%m-%d").to_string())
        ));
    }
    if let Some(e) = settings.ends_on {
        tests.push(format!(
            "currentdate :value \"le\" \"date\" {}",
            quote(&e.format("%Y-%m-%d").to_string())
        ));
    }
    let mut vacation = format!("vacation :days {}", settings.days);
    if !settings.subject.trim().is_empty() {
        vacation.push_str(&format!(" :subject {}", quote(settings.subject.trim())));
    }
    if !addresses.is_empty() {
        let list: Vec<String> = addresses.iter().map(|a| quote(a)).collect();
        vacation.push_str(&format!(" :addresses [{}]", list.join(", ")));
    }
    // Sieve text uses CRLF line ends; the server converts, so send plain newlines.
    let body = settings.body.replace("\r\n", "\n").replace('\r', "\n");
    vacation.push_str(&format!(" {};", quote(&body)));
    match tests.as_slice() {
        [] => out.push_str(&vacation),
        [one] => out.push_str(&format!("if {one} {{\n  {vacation}\n}}")),
        many => out.push_str(&format!(
            "if allof({}) {{\n  {vacation}\n}}",
            many.join(", ")
        )),
    }
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cond(field: Field, op: Op, value: &str) -> Condition {
        Condition {
            field,
            op,
            value: value.into(),
        }
    }

    fn boss() -> Rule {
        Rule {
            name: "Boss".into(),
            enabled: true,
            match_all: true,
            conditions: vec![cond(Field::From, Op::Contains, "boss@")],
            actions: vec![Action::MoveTo {
                folder: "Boss".into(),
            }],
        }
    }

    #[test]
    fn the_boss_rule_becomes_a_fileinto() {
        let script = rules_script(&[boss()]);
        assert!(
            script.contains("require [\"fileinto\", \"mailbox\"];"),
            "{script}"
        );
        assert!(
            script.contains("if address :contains :all \"from\" \"boss@\" {"),
            "{script}"
        );
        assert!(script.contains("fileinto :create \"Boss\";"), "{script}");
    }

    #[test]
    fn quoting_cannot_be_escaped_from() {
        assert_eq!(quote(r#"a"b\c"#), r#""a\"b\\c""#);
        let mut r = boss();
        r.conditions[0].value = r#"x" ; fileinto "evil"#.into();
        r.actions = vec![Action::MarkRead];
        let script = rules_script(&[r]);
        assert!(script.contains(r#""x\" ; fileinto \"evil""#), "{script}");
        assert!(!script.contains("fileinto :create"), "no injected action");
    }

    #[test]
    fn several_conditions_use_allof_or_anyof() {
        let mut r = boss();
        r.conditions.push(cond(Field::Subject, Op::Is, "Report"));
        assert!(rules_script(&[r.clone()]).contains("allof("));
        r.match_all = false;
        let script = rules_script(&[r]);
        assert!(
            script.contains("anyof(") && script.contains("header :is \"subject\" \"Report\""),
            "{script}"
        );
    }

    #[test]
    fn prefix_and_suffix_escape_the_users_wildcards() {
        let mut r = boss();
        r.conditions = vec![cond(Field::Subject, Op::StartsWith, "[ml] *urgent?")];
        r.actions = vec![Action::Discard];
        let script = rules_script(&[r]);
        assert!(
            script.contains(r#"header :matches "subject" "[ml] \\*urgent\\?*""#),
            "{script}"
        );
        let mut r = boss();
        r.conditions = vec![cond(Field::To, Op::EndsWith, "@x.org")];
        assert!(rules_script(&[r]).contains(r#"address :matches :all "to" "*@x.org""#));
    }

    #[test]
    fn flags_come_before_filing_and_stop_comes_last() {
        let mut r = boss();
        r.actions = vec![
            Action::Stop,
            Action::MoveTo {
                folder: "A/B".into(),
            },
            Action::MarkRead,
        ];
        let script = rules_script(&[r]);
        let seen = script.find("addflag").unwrap();
        let file = script.find("fileinto :create").unwrap();
        let stop = script.find("stop;").unwrap();
        assert!(seen < file && file < stop, "{script}");
        assert!(script.contains("require [\"fileinto\", \"mailbox\", \"imap4flags\"];"));
    }

    #[test]
    fn disabled_rules_and_empty_lists_give_a_valid_empty_script() {
        let mut r = boss();
        r.enabled = false;
        let script = rules_script(&[r]);
        assert!(
            !script.contains("require") && !script.contains("if "),
            "{script}"
        );
        assert!(!rules_script(&[]).contains("require"));
    }

    #[test]
    fn forwarding_keeps_a_copy() {
        let mut r = boss();
        r.actions = vec![Action::Forward {
            address: "me@home.example".into(),
        }];
        assert!(rules_script(&[r]).contains("redirect :copy \"me@home.example\";"));
    }

    #[test]
    fn the_main_script_includes_vacation_then_filters() {
        let main = main_script();
        let v = main.find(VACATION_SCRIPT).unwrap();
        let f = main.find(FILTERS_SCRIPT).unwrap();
        assert!(v < f && main.contains("require [\"include\"];"));
    }

    #[test]
    fn the_autoresponder_script() {
        let d = |s: &str| chrono::NaiveDate::parse_from_str(s, "%Y-%m-%d").ok();
        assert!(!vacation_script(&Autoresponder::default(), &[]).contains("vacation :"));
        let on = Autoresponder {
            enabled: true,
            subject: "Away \"now\"".into(),
            body: "Line one\nLine \"two\"".into(),
            days: 3,
            ..Default::default()
        };
        let script = vacation_script(&on, &["a@x.org".into(), "b@x.org".into()]);
        assert!(script.contains("require [\"vacation\"];"), "{script}");
        assert!(script.contains(r#"vacation :days 3 :subject "Away \"now\"" :addresses ["a@x.org", "b@x.org"] "Line one"#), "{script}");
        assert!(!script.contains("currentdate"));
        let dated = Autoresponder {
            starts_on: d("2025-12-01"),
            ends_on: d("2025-12-24"),
            ..on.clone()
        };
        let script = vacation_script(&dated, &[]);
        assert!(script.contains("\"date\", \"relational\""), "{script}");
        assert!(script.contains("allof(currentdate :value \"ge\" \"date\" \"2025-12-01\", currentdate :value \"le\" \"date\" \"2025-12-24\")"), "{script}");
        let open_ended = Autoresponder {
            starts_on: d("2025-12-01"),
            ..on
        };
        assert!(vacation_script(&open_ended, &[]).contains("if currentdate :value \"ge\""));
    }
}
